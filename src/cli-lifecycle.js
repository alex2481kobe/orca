// Orca's daemon lifecycle: start, stop, status, logs, and the per-user service.
//
// One daemon serves every agent on the machine, and no agent owns it. `start`
// launches it detached, in a session of its own, with its output in the state
// directory's log. The command, and the shell or agent session that ran it, can
// then exit, and the daemon keeps running. `service install` hands the same
// daemon to launchd instead, so it also starts at login and comes back after a
// crash.
//
// A running daemon is found by its instance lock (src/instance-lock.js: a pid
// AND that pid's start time) and its port, never by matching process names.
// Nothing here signals a process it cannot prove owns the state directory, and
// nothing stops running executors without saying so first.

import { spawn, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { inspectInstanceLock, probeProcess } from './instance-lock.js';
import {
  ORCA_DIR,
  SERVER_PATH,
  STATE_SOURCE_LABELS,
  daemonLogPath,
  readConfig,
  resolveConfigDir,
  resolveStateDir,
} from './orca-paths.js';
import { FENCE_STATUS, resolveFence } from './fence.js';
import { fixCommands, shellQuote } from './mcp-connection.js';
import { readApiTokenFile, resolveApiToken } from './api-token.js';
import { nodeRuntimeWarnings, resolveMcpLauncher } from './mcp-orchestrator-bootstrap.js';

export const SERVICE_LABEL = 'com.orca.local';
export const PLIST_MARKER = '<!-- Generated by orca-cli.js service install. Replaced by the next install; removed by service uninstall. -->';
const DEFAULT_PORT = 3000;
const DEFAULT_HOST = '127.0.0.1';
const DEFAULT_START_WAIT_S = 120;
const DEFAULT_STOP_WAIT_S = 60;
const POLL_MS = 200;
const HEALTH_TIMEOUT_MS = 2000;
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

export function which(command, envPath = process.env.PATH) {
  for (const dir of String(envPath || '').split(path.delimiter)) {
    if (!dir) continue;
    const candidate = path.join(dir, command);
    try {
      fs.accessSync(candidate, fs.constants.X_OK);
      return candidate;
    } catch { /* keep looking */ }
  }
  return null;
}

// The advice `start` and `setup` print while Orca has no API token. The policy
// itself (loopback without a token is admin) is unchanged.
export function tokenAdvice(env = process.env) {
  if (env.ORCA_API_TOKEN || String(env.ORCA_API_TOKEN_FILE || '').trim()) return null;
  return [
    'Recommended: set an API token. Without one, every process on this machine is Orca admin and role scoping is advisory; a token is required before you pair a phone.',
    '  Keep it in a file only you can read: (umask 077; openssl rand -hex 32 > ~/.config/orca/api-token)',
    '  then run Orca with ORCA_API_TOKEN_FILE=~/.config/orca/api-token (for the LaunchAgent: service install --token-file ~/.config/orca/api-token).',
    '  Agents never get the token: `connect` gives each client its own scoped credential.',
  ].join('\n');
}

function parsePort(value) {
  const port = Number(value);
  if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error(`--port must be a port number from 1 to 65535, not "${value}".`);
  return port;
}

// PORT from the environment. An ephemeral PORT=0 (tests use it) can never be
// found again, so the lifecycle commands fall back to the default for it.
function environmentPort(value) {
  const port = Number(value);
  return Number.isInteger(port) && port >= 1 && port <= 65535 ? port : DEFAULT_PORT;
}

// Everything a lifecycle command resolves, from the same sources as the daemon.
export function lifecycleContext(flags = {}, { env = process.env, home = os.homedir() } = {}) {
  const configDir = resolveConfigDir({ env, home });
  const { config, path: configPath, error: configError } = readConfig({ env, home });
  const state = resolveStateDir({ env, home, config: configError ? null : config });
  const port = flags.port !== undefined ? parsePort(flags.port) : environmentPort(env.PORT);
  const host = String(flags.host ?? env.ORCA_HOST ?? DEFAULT_HOST);
  return {
    env,
    home,
    configDir,
    configPath,
    configError,
    state,
    port,
    host,
    fence: resolveFence({ env, config, configPath, configError }),
    logFile: daemonLogPath(state.dir),
    plistPath: path.join(home, 'Library', 'LaunchAgents', `${SERVICE_LABEL}.plist`),
  };
}

// The URL a local client reaches the listener on (a wildcard bind is reached on loopback).
function urlFor(host, port) {
  const reachable = host === '0.0.0.0' || host === '::' ? '127.0.0.1' : host;
  return `http://${reachable.includes(':') ? `[${reachable}]` : reachable}:${port}`;
}

function inspectDaemon(ctx) {
  let lock;
  try {
    lock = inspectInstanceLock(ctx.state.dir);
  } catch (error) {
    lock = { held: true, reason: 'unreadable', message: `[orca] ${ctx.state.dir} cannot be inspected: ${error.message}` };
  }
  const holder = lock.holder || null;
  const url = lock.held && holder?.listen?.port ? urlFor(holder.listen.host, holder.listen.port) : null;
  return { lock, holder, url, running: Boolean(lock.held && lock.reason === 'running') };
}

// -> 'ok' | 'starting' | 'not-orca' | 'down'
async function probeHealth(url) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), HEALTH_TIMEOUT_MS);
  try {
    const res = await fetch(`${url}/api/health`, { headers: { accept: 'application/json' }, signal: controller.signal });
    const text = await res.text();
    let json = null;
    try { json = JSON.parse(text); } catch { /* not JSON */ }
    if (res.status === 200 && json?.status === 'ok') return 'ok';
    if (res.status === 503 && json && typeof json.error === 'string') return 'starting';
    return 'not-orca';
  } catch (error) {
    const code = error?.cause?.code || error?.code;
    return code === 'ECONNREFUSED' ? 'down' : (error?.name === 'AbortError' ? 'not-orca' : 'down');
  } finally {
    clearTimeout(timer);
  }
}

// Executors that stopping Orca would stop. null when it cannot tell.
async function liveExecutors(url, env) {
  try {
    const headers = { accept: 'application/json' };
    const { token } = resolveApiToken(env);
    if (token) headers['x-orca-token'] = token;
    const res = await fetch(`${url}/api/overview`, { headers, signal: AbortSignal.timeout(5000) });
    if (res.status === 401 || res.status === 403) return { error: 'Orca requires its API token for that; set ORCA_API_TOKEN or ORCA_API_TOKEN_FILE in this command\'s environment' };
    if (res.status !== 200) return { error: `Orca answered HTTP ${res.status}` };
    const overview = await res.json();
    const lanes = [];
    for (const project of overview.projects || []) {
      for (const orchestrator of project.orchestrators || []) {
        for (const executor of orchestrator.executors || []) {
          if (!executor.terminal) lanes.push(`${executor.title} (${executor.id}, ${executor.state})`);
        }
      }
    }
    return { lanes };
  } catch (error) {
    return { error: `Orca did not answer (${error?.cause?.code || error?.message || error})` };
  }
}

// ---- launchd ------------------------------------------------------------------

function launchctl(args) {
  const binary = which('launchctl') || '/bin/launchctl';
  return spawnSync(binary, args, { encoding: 'utf8' });
}

const serviceDomain = () => `gui/${process.getuid()}`;
const serviceTarget = () => `${serviceDomain()}/${SERVICE_LABEL}`;

function serviceState(ctx) {
  if (process.platform !== 'darwin') return { supported: false, installed: false, loaded: false, generated: false, plistPath: null };
  const installed = fs.existsSync(ctx.plistPath);
  let generated = false;
  if (installed) {
    try { generated = fs.readFileSync(ctx.plistPath, 'utf8').includes(PLIST_MARKER); } catch { generated = false; }
  }
  // Ask launchd only when an Orca plist exists: status and start on a machine
  // without the service never call launchctl.
  const loaded = installed ? launchctl(['print', serviceTarget()]).status === 0 : false;
  return { supported: true, installed, loaded, generated, plistPath: ctx.plistPath };
}

const xml = (value) => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// A secret-free per-user LaunchAgent. Absolute paths only: launchd starts jobs
// with a minimal environment and never reads a shell profile. PATH is captured
// so executors can find the agent CLIs (codex, claude) by name.
export function buildLaunchAgentPlist({ node, server = SERVER_PATH, workingDirectory = ORCA_DIR, stateDir, configDir, logFile, pathEnv, port, host, tokenFile = null }) {
  // The token file's PATH, never the token (src/api-token.js).
  const env = { ORCA_CONFIG_DIR: configDir, ORCA_STATE_DIR: stateDir, PATH: pathEnv, PORT: String(port), ORCA_HOST: host, ORCA_API_TOKEN_FILE: tokenFile };
  const envLines = Object.entries(env)
    .filter(([, value]) => value !== undefined && value !== null && value !== '')
    .map(([key, value]) => `    <key>${xml(key)}</key>\n    <string>${xml(value)}</string>`)
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
${PLIST_MARKER}
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${xml(SERVICE_LABEL)}</string>
  <key>ProgramArguments</key>
  <array>
    <string>${xml(node)}</string>
    <string>${xml(server)}</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${xml(workingDirectory)}</string>
  <key>EnvironmentVariables</key>
  <dict>
${envLines}
  </dict>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key>
    <false/>
  </dict>
  <key>ThrottleInterval</key>
  <integer>10</integer>
  <key>StandardOutPath</key>
  <string>${xml(logFile)}</string>
  <key>StandardErrorPath</key>
  <string>${xml(logFile)}</string>
</dict>
</plist>
`;
}

// ---- shared reporting ---------------------------------------------------------

function fenceLine(fence) {
  if (fence.status === FENCE_STATUS.CONFIGURED) {
    return fence.warnings.length ? `${fence.summary}\n    WARNING: ${fence.warnings.join(' ')}` : fence.summary;
  }
  return `SETUP REQUIRED. ${fence.summary}\n    Run: ${fence.fix}`;
}

function stateLine(ctx) {
  return `${ctx.state.dir} (${STATE_SOURCE_LABELS[ctx.state.source] || ctx.state.source})`;
}

function tailFile(file, lines) {
  try {
    const text = fs.readFileSync(file, 'utf8');
    return text.split('\n').slice(-(lines + 1)).join('\n').trimEnd();
  } catch {
    return null;
  }
}

async function waitForDaemon(ctx, { pid = null, child = null, waitMs }) {
  const deadline = Date.now() + waitMs;
  let exit = null;
  child?.once('exit', (code, signal) => { exit = { code, signal }; });
  let seen = null;
  while (Date.now() < deadline) {
    if (exit) return { exited: exit };
    const daemon = inspectDaemon(ctx);
    if (daemon.running && (!pid || daemon.holder.pid === pid)) {
      seen = daemon;
      if (daemon.url && await probeHealth(daemon.url) === 'ok') return { ready: daemon };
    }
    await sleep(POLL_MS);
  }
  return exit ? { exited: exit } : { timedOut: true, seen };
}

function waitSeconds(flags, fallback) {
  if (flags.wait === undefined) return fallback;
  const value = Number(flags.wait);
  if (!Number.isFinite(value) || value < 0) throw new Error(`--wait must be a number of seconds, not "${flags.wait}".`);
  return value;
}

// ---- start --------------------------------------------------------------------

export async function start(flags, out) {
  const ctx = lifecycleContext(flags);
  const daemon = inspectDaemon(ctx);
  if (daemon.running) {
    const health = daemon.url ? await probeHealth(daemon.url) : 'down';
    out.log(`Orca is already running: pid ${daemon.holder.pid}${daemon.url ? `, ${daemon.url}` : ''}. Nothing was changed.`);
    out.log(`  state  ${stateLine(ctx)}`);
    if (health === 'starting') out.log('  It is still starting (loading its state).');
    return 0;
  }
  if (daemon.lock.held) {
    out.err(daemon.lock.message);
    return 1;
  }
  const target = urlFor(ctx.host, ctx.port);
  const health = await probeHealth(target);
  if (health === 'ok' || health === 'starting') {
    out.err([
      `An Orca daemon already answers at ${target}, but it does not own ${ctx.state.dir}: it runs with another state directory. Nothing was changed.`,
      `See which one it is with ${fixCommands.status()}, or give this one another port with --port.`,
    ].join('\n'));
    return 1;
  }
  if (health === 'not-orca') {
    out.err(`Port ${ctx.port} on ${ctx.host} is in use by something that is not Orca. Nothing was changed. Free the port, or start Orca on another one: ${fixCommands.start()} --port <port>`);
    return 1;
  }

  const waitMs = waitSeconds(flags, DEFAULT_START_WAIT_S) * 1000;
  const service = serviceState(ctx);
  let child = null;
  if (service.installed) {
    // The service owns the daemon: launchd starts it, so KeepAlive and the
    // detached start can never both run one.
    const result = service.loaded
      ? launchctl(['kickstart', serviceTarget()])
      : launchctl(['bootstrap', serviceDomain(), ctx.plistPath]);
    if (result.status !== 0) {
      out.err(`launchctl could not start ${SERVICE_LABEL} (exit ${result.status}): ${String(result.stderr || result.stdout || '').trim()}`);
      return 1;
    }
    out.log(`Started the ${SERVICE_LABEL} LaunchAgent (${ctx.plistPath}).`);
  } else {
    fs.mkdirSync(path.dirname(ctx.logFile), { recursive: true, mode: 0o700 });
    const fd = fs.openSync(ctx.logFile, 'a', 0o600);
    try {
      child = spawn(process.execPath, [SERVER_PATH], {
        cwd: ORCA_DIR,
        detached: true,
        stdio: ['ignore', fd, fd],
        env: { ...ctx.env, ORCA_STATE_DIR: ctx.state.dir, ORCA_CONFIG_DIR: ctx.configDir, PORT: String(ctx.port), ORCA_HOST: ctx.host },
      });
    } finally {
      fs.closeSync(fd);
    }
    child.unref();
  }
  if (waitMs === 0) {
    out.log(`Orca is starting${child ? ` (pid ${child.pid})` : ''}. Check it with: ${fixCommands.status()}`);
    return 0;
  }
  const result = await waitForDaemon(ctx, { pid: child?.pid || null, child, waitMs });
  if (result.exited) {
    out.err(`Orca did not start (exit ${result.exited.code ?? result.exited.signal}). The end of ${ctx.logFile}:`);
    out.err(tailFile(ctx.logFile, 20) || '(empty)');
    return 1;
  }
  if (result.timedOut) {
    if (result.seen) {
      out.log(`Orca (pid ${result.seen.holder.pid}) is still starting: it holds its state directory but is not answering yet. Check it with: ${fixCommands.status()}`);
      return 0;
    }
    out.err(`Orca did not come up within ${waitMs / 1000} s. Check ${fixCommands.status()} and the log, ${ctx.logFile}.`);
    return 1;
  }
  const { ready } = result;
  out.log(`Orca is running: pid ${ready.holder.pid}, ${ready.url}.`);
  out.log(`  state  ${stateLine(ctx)}`);
  out.log(`  log    ${ctx.logFile}`);
  out.log(`  fence  ${fenceLine(ctx.fence)}`);
  out.log(service.installed
    ? '  launchd owns it: it restarts after a crash and starts at login.'
    : '  It runs in a session of its own: closing this terminal, or ending the agent session that ran this, does not stop it.');
  out.log(`  Stop it with: ${fixCommands.stop()}`);
  const advice = tokenAdvice(ctx.env);
  if (advice) out.log(advice);
  return 0;
}

// ---- stop ---------------------------------------------------------------------

async function refuseIfExecutorsRunning(url, ctx, flags, out) {
  if (flags.force || !url) return false;
  const live = await liveExecutors(url, ctx.env);
  if (live.error) {
    out.err(`Not stopping: stopping Orca stops every executor it runs, and this command could not check for running ones (${live.error}). Re-run with --force to stop it anyway.`);
    return true;
  }
  if (live.lanes.length) {
    out.err([
      `Not stopping: ${live.lanes.length} executor(s) are running, and stopping Orca stops them. Nothing resumes that work afterwards.`,
      ...live.lanes.map((lane) => `  ${lane}`),
      'Wait for them to finish (or stop them from their orchestrator), or re-run with --force.',
    ].join('\n'));
    return true;
  }
  return false;
}

async function waitForRelease(ctx, waitMs) {
  const deadline = Date.now() + waitMs;
  while (Date.now() < deadline) {
    if (!inspectDaemon(ctx).lock.held) return true;
    await sleep(POLL_MS);
  }
  return false;
}

export async function stop(flags, out) {
  const ctx = lifecycleContext(flags);
  const daemon = inspectDaemon(ctx);
  const service = serviceState(ctx);
  if (!daemon.lock.held && !service.loaded) {
    const target = urlFor(ctx.host, ctx.port);
    const health = await probeHealth(target);
    if (health === 'ok' || health === 'starting') {
      out.err(`No daemon owns ${ctx.state.dir}, but an Orca daemon answers at ${target}: it runs with another state directory. Not stopping it.`);
      return 1;
    }
    out.log(`Orca is not running: no daemon owns ${ctx.state.dir}. Nothing to stop.`);
    return 0;
  }
  if (daemon.lock.held && !daemon.running) {
    out.err(daemon.lock.message);
    return 1;
  }
  if (await refuseIfExecutorsRunning(daemon.url, ctx, flags, out)) return 1;

  const waitMs = waitSeconds(flags, DEFAULT_STOP_WAIT_S) * 1000;
  if (service.loaded) {
    // Unloading is the only stop KeepAlive respects; a signal alone is a restart.
    const result = launchctl(['bootout', serviceTarget()]);
    if (result.status !== 0) {
      out.err(`launchctl could not unload ${SERVICE_LABEL} (exit ${result.status}): ${String(result.stderr || result.stdout || '').trim()}`);
      return 1;
    }
  } else {
    const { holder } = daemon;
    const proc = probeProcess(holder.pid);
    if (proc.state !== 'alive' || !holder.processStart || proc.start !== holder.processStart) {
      out.err(`Not stopping: pid ${holder.pid} cannot be proven to be the daemon that owns ${ctx.state.dir} (its start time does not match the lock). No signal was sent.`);
      return 1;
    }
    try {
      process.kill(holder.pid, 'SIGTERM');
    } catch (error) {
      out.err(`Could not signal pid ${holder.pid}: ${error.message}`);
      return 1;
    }
  }
  if (!(await waitForRelease(ctx, waitMs))) {
    out.err(`Orca is still stopping after ${waitMs / 1000} s (it stops its executors and saves its state first). Check it with: ${fixCommands.status()}`);
    return 1;
  }
  out.log(`Orca stopped${daemon.holder ? ` (pid ${daemon.holder.pid})` : ''}.${service.loaded ? ` The ${SERVICE_LABEL} LaunchAgent is unloaded; \`start\` loads it again.` : ''}`);
  return 0;
}

// ---- status -------------------------------------------------------------------

export async function status(flags, out) {
  const ctx = lifecycleContext(flags);
  const daemon = inspectDaemon(ctx);
  const service = serviceState(ctx);
  let state;
  let url = daemon.url;
  if (daemon.running) {
    state = daemon.url && await probeHealth(daemon.url) === 'ok' ? 'running' : 'starting';
  } else if (daemon.lock.held) {
    state = 'unknown';
  } else {
    url = urlFor(ctx.host, ctx.port);
    const health = await probeHealth(url);
    state = health === 'ok' || health === 'starting' ? 'other-state-dir' : (health === 'not-orca' ? 'port-in-use' : 'stopped');
    if (state === 'stopped') url = null;
  }
  const report = {
    state,
    pid: daemon.running ? daemon.holder.pid : null,
    url,
    stateDir: ctx.state.dir,
    stateSource: ctx.state.source,
    configPath: ctx.configPath,
    logFile: ctx.logFile,
    fence: { status: ctx.fence.status, source: ctx.fence.source, roots: ctx.fence.roots, summary: ctx.fence.summary, fix: ctx.fence.fix, warnings: ctx.fence.warnings },
    service,
    apiTokenInEnvironment: Boolean(ctx.env.ORCA_API_TOKEN),
  };
  if (flags.json) {
    out.log(JSON.stringify(report, null, 2));
  } else {
    const headline = {
      running: `Orca is running: pid ${report.pid}, ${url}.`,
      starting: `Orca is starting: pid ${report.pid} owns the state directory but is not answering yet.`,
      unknown: daemon.lock.message,
      'other-state-dir': `Orca is not running on ${ctx.state.dir}, but an Orca daemon with another state directory answers at ${url}.`,
      'port-in-use': `Orca is not running, and something that is not Orca holds ${url}.`,
      stopped: `Orca is not running. Start it with: ${fixCommands.start()}`,
    }[state];
    out.log(headline);
    out.log(`  state    ${stateLine(ctx)}`);
    out.log(`  config   ${ctx.configPath}${ctx.configError ? ` (${ctx.configError})` : ''}`);
    out.log(`  log      ${ctx.logFile}`);
    out.log(`  fence    ${fenceLine(ctx.fence)}`);
    if (service.supported) {
      out.log(`  service  ${service.installed ? `${SERVICE_LABEL} installed (${service.plistPath}), ${service.loaded ? 'loaded' : 'not loaded'}` : 'not installed'}`);
    }
  }
  if (state === 'running' || state === 'starting') return 0;
  return state === 'stopped' ? 3 : 1;
}

// ---- logs ---------------------------------------------------------------------

export async function logs(flags, out) {
  const ctx = lifecycleContext(flags);
  const count = flags.lines === undefined ? 50 : Number(flags.lines);
  if (!Number.isInteger(count) || count < 1) throw new Error(`--lines must be a positive whole number, not "${flags.lines}".`);
  const text = tailFile(ctx.logFile, count);
  if (text === null) {
    out.err(`There is no daemon log at ${ctx.logFile} yet: Orca writes it when \`start\` or the service runs it.`);
    return 1;
  }
  out.log(text);
  return 0;
}

// ---- service ------------------------------------------------------------------

const LINUX_NOTE = 'service install manages a per-user macOS LaunchAgent. On Linux, run Orca under a systemd --user unit instead: docs/macos-launchd-runbook.md, "Linux: systemd --user".';

function defaultServiceNode() {
  try { return resolveMcpLauncher({}).runtime.nodePath; } catch { return process.execPath; }
}

export async function serviceInstall(flags, out) {
  if (process.platform !== 'darwin' && !flags['dry-run']) {
    out.err(LINUX_NOTE);
    return 2;
  }
  const ctx = lifecycleContext(flags);
  // The plist outlives Node upgrades, so prefer the version-independent path
  // this Node answers to on PATH (a version manager's default alias) over
  // process.execPath, which names one installed version and goes away with it.
  // Exactly what `connect` writes into a client config, so the two agree.
  const node = flags.node ? path.resolve(String(flags.node)) : defaultServiceNode();
  try {
    fs.accessSync(node, fs.constants.X_OK);
  } catch {
    out.err(`--node ${node} is not an executable file.`);
    return 2;
  }
  const tokenFileSetting = flags['token-file'] !== undefined ? String(flags['token-file']) : String(ctx.env.ORCA_API_TOKEN_FILE || '');
  let tokenFile = null;
  if (tokenFileSetting.trim()) {
    const checked = readApiTokenFile(tokenFileSetting);
    if (checked.error) {
      out.err(`${checked.error.replace('ORCA_API_TOKEN_FILE', '--token-file')}`);
      return 2;
    }
    tokenFile = path.resolve(tokenFileSetting.trim());
  }
  const plist = buildLaunchAgentPlist({
    node,
    stateDir: ctx.state.dir,
    configDir: ctx.configDir,
    logFile: ctx.logFile,
    pathEnv: ctx.env.PATH,
    port: ctx.port,
    host: ctx.host,
    tokenFile,
  });
  // A LaunchAgent runs Orca at every login with no session watching it, so a
  // Node that belongs to another tool (or to one installed version) is a boot
  // failure waiting to happen. Orca does not manage toolchains: it says so, and
  // names --node. It does not refuse — on a workstation whose only Node is a
  // version manager's, refusing would break the one-command install.
  const nodeWarnings = nodeRuntimeWarnings(node);
  const summary = [
    `  node    ${node}`,
    ...nodeWarnings.map((warning) => `          WARNING: ${warning} launchd starts this at every login with nothing watching; re-run with --node <a Node you maintain> --replace to change it.`),
    `  state   ${stateLine(ctx)}`,
    `  config  ${ctx.configDir}`,
    `  log     ${ctx.logFile}`,
    `  listen  ${urlFor(ctx.host, ctx.port)}`,
    `  token   ${tokenFile ? `${tokenFile} (the plist names the file, never the token)` : 'none: every local process will be Orca admin. Pass --token-file PATH (an owner-only file) to protect it.'}`,
  ];
  if (!tokenFile && ctx.env.ORCA_API_TOKEN) {
    summary.push('  Note: ORCA_API_TOKEN is set here, but a plist must never hold it, so the service would run without it. Put it in an owner-only file and pass --token-file.');
  }
  if (flags['dry-run']) {
    out.log(`Would write ${ctx.plistPath}:`);
    out.log(summary.join('\n'));
    out.log(plist);
    return 0;
  }
  const service = serviceState(ctx);
  if (service.installed && !service.generated && !flags.replace) {
    out.err(`Not replacing ${ctx.plistPath}: it was not generated by orca-cli.js (it may be the runbook's manual LaunchAgent, whose wrapper loads your API token). Re-run with --replace to replace it.`);
    return 1;
  }
  if (service.loaded) {
    out.err(`The ${SERVICE_LABEL} LaunchAgent is loaded. Stop it first (${fixCommands.stop()}, which unloads it), then install again.`);
    return 1;
  }
  const daemon = inspectDaemon(ctx);
  fs.mkdirSync(path.dirname(ctx.plistPath), { recursive: true });
  fs.mkdirSync(path.dirname(ctx.logFile), { recursive: true, mode: 0o700 });
  const temp = `${ctx.plistPath}.${process.pid}.tmp`;
  fs.writeFileSync(temp, plist, { mode: 0o644 });
  fs.renameSync(temp, ctx.plistPath);
  out.log(`Wrote ${ctx.plistPath} (no secrets: the API token is never written to it).`);
  out.log(summary.join('\n'));
  if (daemon.running) {
    out.log(`Orca is already running outside the service (pid ${daemon.holder.pid}), so the service is not loaded now: launchd's start would be refused while that daemon owns ${ctx.state.dir}.`);
    out.log(`When no executors are running: ${fixCommands.stop()} && ${fixCommands.start()} — start then runs Orca under launchd.`);
    return 0;
  }
  if (flags['no-load']) {
    out.log(`Not loaded (--no-load). \`${fixCommands.start()}\` loads it.`);
    return 0;
  }
  const loaded = launchctl(['bootstrap', serviceDomain(), ctx.plistPath]);
  if (loaded.status !== 0) {
    out.err(`launchctl could not load ${ctx.plistPath} (exit ${loaded.status}): ${String(loaded.stderr || loaded.stdout || '').trim()}`);
    return 1;
  }
  out.log(`Loaded ${SERVICE_LABEL}: launchd starts Orca now, at every login, and again after a crash.`);
  const waitMs = waitSeconds(flags, DEFAULT_START_WAIT_S) * 1000;
  if (waitMs === 0) {
    out.log(`Check it with: ${fixCommands.status()}`);
    return 0;
  }
  const result = await waitForDaemon(ctx, { waitMs });
  if (result.ready) {
    out.log(`Orca is running: pid ${result.ready.holder.pid}, ${result.ready.url}.`);
    const advice = tokenAdvice(ctx.env);
    if (advice) out.log(advice);
    return 0;
  }
  out.err(`Orca did not come up within ${waitMs / 1000} s under launchd. Check ${fixCommands.status()} and the log, ${ctx.logFile}.`);
  return 1;
}

export async function serviceUninstall(flags, out) {
  if (process.platform !== 'darwin') {
    out.err(LINUX_NOTE);
    return 2;
  }
  const ctx = lifecycleContext(flags);
  const service = serviceState(ctx);
  if (!service.installed) {
    out.log(`No Orca LaunchAgent is installed at ${ctx.plistPath}. Nothing to remove.`);
    return 0;
  }
  if (!service.generated && !flags.force) {
    out.err(`Not removing ${ctx.plistPath}: it was not generated by orca-cli.js. Re-run with --force to remove it anyway.`);
    return 1;
  }
  if (service.loaded) {
    const daemon = inspectDaemon(ctx);
    if (await refuseIfExecutorsRunning(daemon.url, ctx, flags, out)) return 1;
    const result = launchctl(['bootout', serviceTarget()]);
    if (result.status !== 0) {
      out.err(`launchctl could not unload ${SERVICE_LABEL} (exit ${result.status}): ${String(result.stderr || result.stdout || '').trim()}`);
      return 1;
    }
  }
  fs.unlinkSync(ctx.plistPath);
  out.log(`Removed ${ctx.plistPath}${service.loaded ? ' and unloaded it (Orca stopped)' : ''}. Orca's state (${ctx.state.dir}) and config (${ctx.configDir}) are untouched.`);
  return 0;
}

